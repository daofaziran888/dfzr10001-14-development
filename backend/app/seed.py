def _buckets(*ages: tuple[int, int]) -> list[dict[str, Any]]:
    """按相对今天的采集时间构造分区明细桶：(几天前采集, 记录条数)。"""
    today = date.today()
    return [
        {"采集时间": (today - timedelta(days=age)).isoformat(), "记录条数": count}
        for age, count in ages
    ]


